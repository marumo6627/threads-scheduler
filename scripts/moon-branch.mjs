// moon の時刻分岐の「固定ブロック」を日付で回す。
// 2026-10-10 追加。10行中7行が毎日同じで、前日との一致率が最悪70%だった。
// 変えるのは 2行目 / 分岐の右側 / 絵文字の並び / CTA の4か所。
// ★右側は時間帯と矛盾してはいけない（19時台に「朝のうちに」が出た）。
//   枠ごとの時刻表現＋どの枠でも成り立つ順番表現、の中から選ぶ。
export const LEAD = [
  '見た時間で、今日の進み方が変わりそうです',
  '何時に開いたかで、流れが少し違うようです',
  '見た時間によって、向いていることが変わるみたいです',
  'この時間に見た方には、こんな順番が来ているようです',
  '開いた時刻が、今日の組み立てを決めるようです',
];
// 枠の「時」→ その枠で意味が通る時刻表現
const BY_HOUR = {
  5:  ['朝のうちに', '午前のうちに', 'お昼すぎに', '夕方に'],
  10: ['お昼までに', '午後いちで', '夕方までに', '今夜のうちに'],
  16: ['夕方のうちに', '夜ごはんの前に', 'お風呂の前に', '寝る前に'],
  19: ['今夜のうちに', 'お風呂の前に', '寝る前に', '明日の朝に'],
};
// 時刻に依存しない順番表現（どの枠でも使える）
const ORDER = [
  ['いちばん先に', '二番目に', '落ち着いてから', '最後に'],
  ['すぐに', '少しあとで', 'もう少し先で', '最後でいい'],
  ['先に一つ', '次に一つ', 'そのあとで', '余力があれば'],
];
export const EMO = [
  ['🌙', '✨', '🤍', '🦋'], ['🤍', '🦋', '🌙', '✨'],
  ['🦋', '🌙', '✨', '🤍'], ['✨', '🤍', '🦋', '🌙'],
  ['🌙', '🤍', '✨', '🦋'],
];
export const CTA = [
  '見た時間の絵文字を置いていってね。',
  '見た時間の絵文字を、ひとつ置いていってください。',
  'あなたが開いた時間の絵文字を置いていってね。',
  '当てはまる時間の絵文字だけ置いていってください。',
  '見た時刻の絵文字を置いていってくれたら、それで十分です。',
];
const pick = (date, time, pool, shift = 0) => {
  const dn = Number(date.replace(/-/g, '').slice(-4));
  const tn = Number(time.slice(0, 2));
  return pool[(dn + tn + shift) % pool.length];
};
export const build = (date, time, hook, bands, body, due) => {
  const hour = Number(time.slice(0, 2));
  const acts = [BY_HOUR[hour] || BY_HOUR[5], ...ORDER];
  const emo = pick(date, time, EMO);
  const act = pick(date, time, acts, 1);
  const rows = bands.map((b, i) => `『${emo[i]}』${b}　→　${act[i]}`);
  return [hook, pick(date, time, LEAD, 2), '', ...rows, '', ...body, '', due, '', pick(date, time, CTA, 3)].join('\n');
};
